"""Generate snowflake/50_semantic/column_masking.sql from seeds/column_groups.csv.

One masking policy per column group and data type, attached to every protected column of the semantic views.
Identity columns (dates, client, campaign, media type ...) are never masked: they are what rows are filtered by.
    python scripts/gen_column_masking.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VIEW = "GOLD.SEMANTIC.V_MEDIA_PERFORMANCE_DAILY"
NUMBER = {"impressions", "clicks", "video_starts", "completed_plays", "post_shares", "spots", "spend", "conversions",
          "platform_conversions", "platform_all_conversions", "click_through_conversions", "view_through_conversions",
          "revenue"}
IN_VIEW = NUMBER | {"currency_code", "conversion_tag", "kpi_group", "source_name", "loaded_from", "job_number",
                    "campaign_name_valid", "counts_toward_kpi", "row_type"}
TYPES = {"campaign_name_valid": "boolean", "counts_toward_kpi": "boolean"}


def main():
    groups = list(csv.DictReader(open(ROOT / "seeds" / "column_groups.csv")))
    out = ["-- Generated by scripts/gen_column_masking.py from seeds/column_groups.csv. Do not edit by hand.",
           "use role EPITAPH_TRANSFORMER;", ""]
    attach = []
    for g in groups:
        name = g["column_group"]
        if name == "identity":
            continue
        cols = [c.strip() for c in g["columns"].split(",") if c.strip() in IN_VIEW]
        if not cols:
            continue
        kinds = {("number" if c in NUMBER else TYPES.get(c, "varchar")) for c in cols}
        for k in sorted(kinds):
            out.append(f"create masking policy if not exists GOLD.CONTROL.MASK_{name.upper()}_{k.upper()} as (val {k}) "
                       f"returns {k} -> iff(GOLD.CONTROL.CAN_SEE('{name}'), val, null);")
        for c in cols:
            k = "number" if c in NUMBER else TYPES.get(c, "varchar")
            attach.append(f"alter view {VIEW} modify column {c} set masking policy GOLD.CONTROL.MASK_{name.upper()}_{k.upper()} force;")
    out += [""] + attach
    (ROOT / "snowflake" / "50_semantic" / "column_masking.sql").write_text("\n".join(out) + "\n")
    print(f"{len(attach)} columns protected")


if __name__ == "__main__":
    main()
