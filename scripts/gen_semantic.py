"""Generate snowflake/50_semantic/v_kpi_definitions.sql from config/kpis.yml.

The KPI definitions live in one place (config/kpis.yml). This writes them into Snowflake as a view so anyone can
query what a KPI means, and the Omni build reads the same file, so the two never drift apart.

    python scripts/gen_semantic.py
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (list, tuple)):
        v = ", ".join(str(x) for x in v)
    return "'" + str(v).replace("'", "''") + "'"


def main():
    k = yaml.safe_load(open(ROOT / "config" / "kpis.yml"))
    rows = []
    for x in k["kpis"]:
        rows.append("  (" + ", ".join(q(x.get(f)) for f in
                    ("name", "type", "expr", "format", "fact", "decision", "status", "tapclicks", "notes")) + ", "
                    + q(bool(x.get("not_additive"))) + ")")
    for x in k.get("retired", []):
        rows.append("  (" + ", ".join([q(x["name"]), "'retired'", "null", "null", "null", q(x["decision"]), "'retired'",
                                       q(x.get("tapclicks")), q(x.get("reason") or x.get("replaced_by"))]) + ", false)")
    sql = ("-- Generated by scripts/gen_semantic.py from config/kpis.yml. Do not edit by hand.\n"
           "use role EPITAPH_TRANSFORMER;\n\n"
           "create or replace view GOLD.SEMANTIC.V_KPI_DEFINITIONS as\n"
           "select column1 as kpi_name, column2 as kpi_type, column3 as formula, column4 as format, column5 as fact,\n"
           "       column6 as decision, column7 as status, column8 as replaces_tapclicks_kpis, column9 as notes,\n"
           "       column10 as not_additive\n"
           "from values\n" + ",\n".join(rows) + ";\n")
    out = ROOT / "snowflake" / "50_semantic" / "v_kpi_definitions.sql"
    out.write_text(sql)
    print(f"{len(rows)} KPI rows written to {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
